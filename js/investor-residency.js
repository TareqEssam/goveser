document.addEventListener('DOMContentLoaded', () => {
  // Wait for main.js Lang to be ready
  const applyPageLang = (lang) => {
    const t = pageTranslations[lang];
    if (!t) return;

    // Update page title
    document.title = t['page.title'];

    // Translate all data-p18n elements (page-specific keys)
    document.querySelectorAll('[data-p18n]').forEach(el => {
      const key = el.dataset.p18n;
      const val = t[key];
      if (val === undefined) return;
      // Allow HTML content for rich text
      if (el.dataset.p18nHtml !== undefined || val.includes('<')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    });
    document.querySelectorAll('[data-p18n-aria-label]').forEach(el => {
      const value = t[el.dataset.p18nAriaLabel];
      if (value !== undefined) el.setAttribute('aria-label', value);
    });

    // Arrow direction for card links
    document.querySelectorAll('.card-link-arrow').forEach(arrow => {
      arrow.textContent = lang === 'ar' ? '←' : '→';
    });
  };

  // Hook into the main Lang.set
  const originalSet = window.Lang ? window.Lang.set.bind(window.Lang) : null;
  if (originalSet) {
    window.Lang.set = function(lang, animate) {
      originalSet(lang, animate);
      applyPageLang(lang);
    };
    // Apply current language on load
    applyPageLang(window.Lang.current || localStorage.getItem('goveser-lang') || 'ar');
  } else {
    // Fallback: wait a tick for main.js to load
    setTimeout(() => {
      const lang = localStorage.getItem('goveser-lang') || 'ar';
      applyPageLang(lang);
    }, 50);
  }

  // Also re-apply when lang buttons are clicked
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      setTimeout(() => applyPageLang(btn.dataset.lang), 10);
    });
  });
});
